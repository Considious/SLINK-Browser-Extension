import assert from 'node:assert/strict';
await import('../src/content/inline-status.js');
const {timers,elapsed,dailyWindow}=globalThis.SLINK_INLINE_STATUS;
const now=1700000000000,at=now-60_000;
const body={cooldowns:{medical:120,booster:999999},education:{current:{until:now/1000+400}},organizedCrime:{ready_at:now/1000+600}};
const war={startedAt:now+500_000,detectedAt:at},virus={at,until:(now+120_000)/1000};
const all=timers({alerts:{data:body,fetchedAt:at},war,virus},now);
assert.deepEqual(Object.keys(all),['oc','war','virus']);assert.equal(all.oc.end,now+600_000);assert.equal(all.virus.end,now+120_000);
assert.deepEqual(timers({alerts:{data:body,fetchedAt:now-61*60000},war:{...war,detectedAt:0},virus:{...virus,until:now/1000-1}},now),{});
assert.equal(timers({alerts:{data:{organizedCrime:{...body.organizedCrime,executed_at:now/1000-5}},fetchedAt:at}},now).oc,undefined);
assert.equal(elapsed(117660000),'1d 8h 41m');assert.equal(elapsed(-60000),'0m');
assert.equal(dailyWindow(Date.parse('2026-11-21T18:15:30Z')),true);assert.equal(dailyWindow(Date.parse('2026-11-21T18:16:00Z')),false);
console.log('Inline status: requested timers only, expiry, upstream timestamps and daily window passed.');
